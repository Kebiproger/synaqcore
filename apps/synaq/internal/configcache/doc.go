//   - явно через Reload (админские ручки после коммита — read-your-writes);
//   - по уведомлениям PostgreSQL LISTEN experiments_changed (с дебаунсом);
//   - периодически (страховка от потерянных уведомлений);
//   - после переподключения слушателя.
//
// При ошибке перечитывания продолжает раздаваться предыдущий (устаревший) снимок.
